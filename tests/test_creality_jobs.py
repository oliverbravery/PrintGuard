    async def test_browser_multipart_wire_preserves_large_file(self):
        """An actual loopback HTTP receiver validates headers and MIME bytes."""
        data = DATA * 25000
        name = m.upload_name("Swatch.gcode", data)
        headers, body = m.upload_form("http://127.0.0.1", name, data)
        received = asyncio.get_running_loop().create_future()

        async def receiver(reader, writer):
            try:
                raw_headers = await reader.readuntil(b"\r\n\r\n")
                line, rest = raw_headers.split(b"\r\n", 1)
                self.assertEqual(line, f"POST /upload/{name} HTTP/1.1".encode())
                parsed = BytesParser(policy=policy.default).parsebytes(rest)
                self.assertEqual(parsed["Origin"], "http://127.0.0.1")
                self.assertEqual(parsed["Referer"], "http://127.0.0.1/")
                self.assertEqual(parsed["Connection"], "close")
                self.assertIsNone(parsed["Transfer-Encoding"])
                self.assertTrue(
                    parsed.get_boundary().startswith("----WebKitFormBoundary")
                )
                payload = await reader.readexactly(int(parsed["Content-Length"]))
                parts = list(
                    BytesParser(policy=policy.default)
                    .parsebytes(rest + payload)
                    .iter_parts()
                )
                self.assertEqual(len(parts), 1)
                self.assertEqual(parts[0].get_filename(), name)
                self.assertEqual(
                    parts[0].get_param("name", header="Content-Disposition"), "file"
                )
                self.assertEqual(parts[0].get_payload(decode=True), data)
                writer.write(
                    b'HTTP/1.1 200 OK\r\nContent-Length: 12\r\nConnection: close\r\n\r\n{"code":200}'
                )
                await writer.drain()
                received.set_result(True)
            except BaseException as error:
                received.set_exception(error)
            finally:
                writer.close()
                await writer.wait_closed()

        server = await asyncio.start_server(receiver, "127.0.0.1", 0)
        async with server, httpx.AsyncClient(trust_env=False, timeout=5) as client:
            port = server.sockets[0].getsockname()[1]
            response = await client.post(
                f"http://127.0.0.1:{port}/upload/{name}", headers=headers, content=body
            )
            self.assertEqual(response.json(), {"code": 200})
            await asyncio.wait_for(received, 5)

