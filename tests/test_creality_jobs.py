    async def emit(self, socket, change):
        self.raw.update(change)
        await socket.send(json.dumps(change))

    async def handler(self, socket):
        self.connections += 1
        try:
            if self.mode == "quiet":
                await socket.wait_closed()
                return
            if self.mode == "partial":
                await socket.send(json.dumps({"model": self.raw["model"]}))
                await asyncio.sleep(0.01)
            await socket.send(json.dumps(self.raw))
            if self.mode == "already-stopping":
                await asyncio.sleep(0.01)
                await self.emit(socket, {"state": 4})
            async for text in socket:
                message = json.loads(text)
                self.commands.append(message)
                params = message["params"]
                await socket.send(text)
                if "reqGcodeFile" in params:
                    if self.mode == "file-ack-only":
                        continue
                    name, data = self.uploaded
                    path = m.GCODE_ROOT + name
                    if self.mode == "file-wrong-name":
                        name = "different.gcode"
                    if self.mode == "file-unsafe-path":
                        path = "/tmp/" + name
                    if self.mode == "file-noncanonical-path":
                        path = m.GCODE_ROOT + "../gcodes/" + name
                    if self.mode == "file-wrong-size":
                        data += b"truncated-or-wrong"
                    change = {
                        "retGcodeFileInfo2": [
                            {"name": name, "file_size": len(data), "path": path}
                        ]
                    }
                    if self.mode == "file-legacy":
                        change = {
                            "retGcodeFileInfo": {
                                "fileInfo": f"{m.GCODE_ROOT.rstrip('/')}:{name}:{len(data)}:1:100;"
                            }
                        }
                    if self.mode == "busy-with-file":
                        change["state"] = 1
                    if self.mode == "offline-with-file":
                        change["connect"] = 0
                    if self.mode == "model-with-file":
                        change["model"] = "F004"
                    await socket.send(json.dumps(change))
                    continue
                if self.mode == "disconnect":
                    await socket.close()
                    return
                if self.mode == "malformed":
                    await socket.send("not-json")
                    continue
                if self.mode == "ack-only":
                    continue
                if self.mode == "offline":
                    await self.emit(socket, {"connect": 0})
                    continue
                if self.mode == "wrong-model":
                    await self.emit(socket, {"model": "F004"})
                    continue
                if "stop" in params:
                    await self.emit(socket, {"state": 7})
                    if self.mode == "stopping-only":
                        continue
                    if self.mode == "idle-only":
                        await self.emit(socket, {"state": 0})
                        continue
                    if self.mode == "transient-idle":
                        await self.emit(socket, {"state": 0})
                    await asyncio.sleep(0.01)
                    await self.emit(socket, {"state": 4})
                elif "opGcodeFile" in params:
                    path = params["opGcodeFile"].removeprefix("printprt:")
                    if self.mode == "start-error":
                        await self.emit(socket, {"state": 3})
                        continue
                    if self.mode == "filename-only":
                        await self.emit(socket, {"printFileName": path})
                        continue
                    if self.mode == "state-only":
                        await self.emit(socket, {"state": 1})
                        continue
                    if self.mode == "wrong-job":
                        await self.emit(
                            socket, {"state": 1, "printFileName": "another.gcode"}
                        )
                        continue
                    if self.mode == "basename":
                        path = path.rsplit("/", 1)[-1]
                    if self.mode == "filename-first":
                        await self.emit(socket, {"printFileName": path})
                        await asyncio.sleep(0.01)
                        await self.emit(socket, {"state": 1})
                    else:
                        await self.emit(socket, {"state": 1})
                        await asyncio.sleep(0.01)
                        await self.emit(socket, {"printFileName": path})
                elif params.get("pause") == 1:
                    await self.emit(socket, {"state": 5})
                elif params.get("pause") == 0:
                    await self.emit(socket, {"state": 1})
        except ConnectionClosed:
            pass

    async def http(self, method, url, **kwargs):
        body = kwargs.get("data")
        if body is not None and not isinstance(body, bytes):
            body = b"".join([part async for part in body])
        self.http_requests.append(
            {"method": method, "url": url, **kwargs, "data": body}
        )
        if method == "GET":
            if self.mode == "info-reset":
                raise httpx.ReadError("simulated reset")
            return (
                (200, {"model": "F004"})
                if self.mode == "http-wrong-model"
                else (200, {"model": "F003"})
            )
        name = unquote(url.rsplit("/", 1)[-1])
        self.assertIn(f'filename="{name}"'.encode(), body)
        self.assertIn(b'name="file"', body)
        self.assertEqual(len(body), int(kwargs["headers"]["Content-Length"]))
        data = body.split(b"\r\n\r\n", 1)[1].rsplit(b"\r\n--", 1)[0]
        self.uploaded = (name, data)
        if self.mode == "http-error":
            return 500, "failed"
        if self.mode == "http-redirect":
            return 302, "redirect"
        if self.mode == "upload-reset":
            raise httpx.ReadError("simulated reset")
        if self.mode == "upload-json-error":
            return 200, {"code": 500, "message": "failed"}
        if self.mode == "upload-unconfirmed":
            return 200, "not a confirmed upload"
        if self.mode == "busy-after-upload":
            self.raw["state"] = 1
        if self.mode == "stale-file-before-query":
            self.raw["retGcodeFileInfo2"] = [
                {"name": name, "file_size": len(data), "path": m.GCODE_ROOT + name}
            ]
            self.mode = "file-ack-only"
        if self.mode == "stale-job-before-start":
            self.raw["printFileName"] = m.GCODE_ROOT + name
            self.mode = "state-only"
        return 200, {"code": 200, "message": "OK"}

