    @asynccontextmanager
    async def engine(self):
        platform = FakePlatform()
        background_http = platform.http

        async def route_http(method, url, **kwargs):
            if url.startswith("http://127.0.0.1/"):
                return await self.http(method, url, **kwargs)
            return await background_http(method, url, **kwargs)

        platform.http = route_http
        engine = Engine(platform)
        with patch.dict(INTEGRATIONS, {self.adapter.id: self.adapter}):
            await engine.start()
            try:
                await engine.request(
                    {
                        "cmd": "printer.add",
                        "printer": {
                            "name": "Loopback fake",
                            "provider": self.adapter.id,
                            "config": self.config,
                        },
                    }
                )
                printer = next(iter(engine.printers.values()))
                platform.files.blobs["jobtest1.gcode"] = DATA
                await engine.request(
                    {
                        "cmd": "print.add",
                        "id": "jobtest1",
                        "filename": "test.gcode",
                        "printer_ids": [printer.id],
                    }
                )
                yield engine, printer
            finally:
                await engine.stop()

